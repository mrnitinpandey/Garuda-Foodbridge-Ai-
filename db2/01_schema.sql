-- ----------------------------------------------------------------------------
-- 1. USERS TABLE
-- ----------------------------------------------------------------------------
CREATE TABLE USERS (
    USER_ID             VARCHAR(36)     NOT NULL,
    NAME                VARCHAR(128)    NOT NULL,
    EMAIL               VARCHAR(128)    NOT NULL,
    PASSWORD_HASH       VARCHAR(255)    NOT NULL,
    ROLE                VARCHAR(20)     NOT NULL DEFAULT 'DONOR',
    PHONE               VARCHAR(32),
    IS_ACTIVE           SMALLINT        NOT NULL DEFAULT 1,
    IS_DEMO_ACCOUNT     SMALLINT        NOT NULL DEFAULT 0,
    CREATED_AT          TIMESTAMP       NOT NULL DEFAULT CURRENT TIMESTAMP,
    UPDATED_AT          TIMESTAMP       NOT NULL DEFAULT CURRENT TIMESTAMP,
    CONSTRAINT PK_USERS PRIMARY KEY (USER_ID),
    CONSTRAINT UQ_USERS_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CHK_USERS_ROLE CHECK (ROLE IN ('DONOR', 'NGO', 'VOLUNTEER', 'ADMIN'))
);

-- ----------------------------------------------------------------------------
-- 2. DONOR_PROFILES TABLE
-- ----------------------------------------------------------------------------
CREATE TABLE DONOR_PROFILES (
    PROFILE_ID          VARCHAR(36)     NOT NULL,
    USER_ID             VARCHAR(36)     NOT NULL,
    ORG_NAME            VARCHAR(150)    NOT NULL,
    ORG_TYPE            VARCHAR(50)     NOT NULL DEFAULT 'COLLEGE_CANTEEN',
    STREET_ADDRESS      VARCHAR(255),
    CITY                VARCHAR(100)    DEFAULT 'Bengaluru',
    STATE               VARCHAR(100)    DEFAULT 'Karnataka',
    ZIP_CODE            VARCHAR(20),
    LONGITUDE           DECIMAL(11, 8)  NOT NULL DEFAULT 77.5946,
    LATITUDE            DECIMAL(10, 8)  NOT NULL DEFAULT 12.9716,
    CONTACT_NAME        VARCHAR(128),
    CONTACT_PHONE       VARCHAR(32),
    CREATED_AT          TIMESTAMP       NOT NULL DEFAULT CURRENT TIMESTAMP,
    UPDATED_AT          TIMESTAMP       NOT NULL DEFAULT CURRENT TIMESTAMP,
    CONSTRAINT PK_DONOR_PROFILES PRIMARY KEY (PROFILE_ID),
    CONSTRAINT FK_DONOR_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE
);

-- ----------------------------------------------------------------------------
-- 3. NGO_PROFILES TABLE
-- ----------------------------------------------------------------------------
CREATE TABLE NGO_PROFILES (
    NGO_ID              VARCHAR(36)     NOT NULL,
    USER_ID             VARCHAR(36)     NOT NULL,
    ORG_NAME            VARCHAR(150)    NOT NULL,
    REGISTRATION_NO     VARCHAR(64),
    VERIFICATION_STATUS VARCHAR(20)     NOT NULL DEFAULT 'PENDING',
    SERVICE_RADIUS_KM   DECIMAL(5, 2)   NOT NULL DEFAULT 15.00,
    MEAL_DEMAND         INTEGER         NOT NULL DEFAULT 100,
    COLLECTION_CAPACITY INTEGER         NOT NULL DEFAULT 150,
    ACCEPTED_CATEGORIES VARCHAR(255)    DEFAULT 'COOKED_MEALS,PACKAGED_FOOD,BAKERY_ITEMS',
    STREET_ADDRESS      VARCHAR(255),
    CITY                VARCHAR(100)    DEFAULT 'Bengaluru',
    LONGITUDE           DECIMAL(11, 8)  NOT NULL DEFAULT 77.6101,
    LATITUDE            DECIMAL(10, 8)  NOT NULL DEFAULT 12.9550,
    HAS_COLD_STORAGE    SMALLINT        NOT NULL DEFAULT 1,
    HAS_INSULATED_BOXES SMALLINT        NOT NULL DEFAULT 1,
    FOOD_SAFETY_CERT    SMALLINT        NOT NULL DEFAULT 1,
    HAS_VEHICLE         SMALLINT        NOT NULL DEFAULT 1,
    VEHICLE_TYPE        VARCHAR(32)     DEFAULT 'AUTO_VAN',
    MAX_LOAD_KG         DECIMAL(7, 2)   DEFAULT 100.00,
    CREATED_AT          TIMESTAMP       NOT NULL DEFAULT CURRENT TIMESTAMP,
    UPDATED_AT          TIMESTAMP       NOT NULL DEFAULT CURRENT TIMESTAMP,
    CONSTRAINT PK_NGO_PROFILES PRIMARY KEY (NGO_ID),
    CONSTRAINT FK_NGO_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE,
    CONSTRAINT CHK_NGO_STATUS CHECK (VERIFICATION_STATUS IN ('PENDING', 'VERIFIED', 'REJECTED', 'SUSPENDED'))
);

-- ----------------------------------------------------------------------------
-- 4. DONATIONS TABLE
-- ----------------------------------------------------------------------------
CREATE TABLE DONATIONS (
    DONATION_ID         VARCHAR(36)     NOT NULL,
    DONOR_ID            VARCHAR(36)     NOT NULL,
    TITLE               VARCHAR(200)    NOT NULL,
    FOOD_CATEGORY       VARCHAR(32)     NOT NULL DEFAULT 'COOKED_MEALS',
    DESCRIPTION         VARCHAR(1000),
    PORTIONS_AVAILABLE  INTEGER         NOT NULL,
    PORTIONS_REMAINING  INTEGER         NOT NULL,
    PREPARED_AT         TIMESTAMP       NOT NULL,
    COLLECTION_DEADLINE TIMESTAMP       NOT NULL,
    STORAGE_CONDITIONS  VARCHAR(32)     DEFAULT 'ROOM_TEMPERATURE',
    FOOD_TEMP_CELSIUS   DECIMAL(5, 2)   DEFAULT 55.0,
    STATUS              VARCHAR(20)     NOT NULL DEFAULT 'AVAILABLE',
    PICKUP_ADDRESS      VARCHAR(255),
    CITY                VARCHAR(100)    DEFAULT 'Bengaluru',
    LONGITUDE           DECIMAL(11, 8)  NOT NULL DEFAULT 77.5946,
    LATITUDE            DECIMAL(10, 8)  NOT NULL DEFAULT 12.9716,
    SAFETY_STATUS       VARCHAR(20)     DEFAULT 'ELIGIBLE',
    CREATED_AT          TIMESTAMP       NOT NULL DEFAULT CURRENT TIMESTAMP,
    UPDATED_AT          TIMESTAMP       NOT NULL DEFAULT CURRENT TIMESTAMP,
    CONSTRAINT PK_DONATIONS PRIMARY KEY (DONATION_ID),
    CONSTRAINT FK_DONATION_DONOR FOREIGN KEY (DONOR_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE,
    CONSTRAINT CHK_DONATION_STATUS CHECK (STATUS IN ('AVAILABLE', 'MATCHED', 'RESERVED', 'PICKED_UP', 'DELIVERED', 'EXPIRED', 'CANCELLED'))
);

-- ----------------------------------------------------------------------------
-- 5. MATCHES TABLE
-- ----------------------------------------------------------------------------
CREATE TABLE MATCHES (
    MATCH_ID            VARCHAR(36)     NOT NULL,
    DONATION_ID         VARCHAR(36)     NOT NULL,
    NGO_ID              VARCHAR(36)     NOT NULL,
    PORTIONS_ALLOCATED  INTEGER         NOT NULL,
    PRIORITY_SCORE      DECIMAL(5, 2)   NOT NULL,
    URGENCY_SCORE       DECIMAL(5, 2)   NOT NULL,
    QUANTITY_FIT_SCORE  DECIMAL(5, 2)   NOT NULL,
    TRAVEL_SCORE        DECIMAL(5, 2)   NOT NULL,
    DEMAND_FIT_SCORE    DECIMAL(5, 2)   NOT NULL,
    EST_TRAVEL_MINUTES  INTEGER,
    EST_DISTANCE_KM     DECIMAL(6, 2),
    RECOMMENDATION_NOTE VARCHAR(500),
    STATUS              VARCHAR(20)     NOT NULL DEFAULT 'PROPOSED',
    CREATED_AT          TIMESTAMP       NOT NULL DEFAULT CURRENT TIMESTAMP,
    CONSTRAINT PK_MATCHES PRIMARY KEY (MATCH_ID),
    CONSTRAINT FK_MATCH_DONATION FOREIGN KEY (DONATION_ID) REFERENCES DONATIONS(DONATION_ID) ON DELETE CASCADE,
    CONSTRAINT FK_MATCH_NGO FOREIGN KEY (NGO_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE,
    CONSTRAINT CHK_MATCH_STATUS CHECK (STATUS IN ('PROPOSED', 'ACCEPTED', 'DECLINED', 'EXPIRED', 'COMPLETED'))
);

-- ----------------------------------------------------------------------------
-- 6. RESCUES TABLE
-- ----------------------------------------------------------------------------
CREATE TABLE RESCUES (
    RESCUE_ID           VARCHAR(36)     NOT NULL,
    DONATION_ID         VARCHAR(36)     NOT NULL,
    MATCH_ID            VARCHAR(36)     NOT NULL,
    DONOR_ID            VARCHAR(36)     NOT NULL,
    NGO_ID              VARCHAR(36)     NOT NULL,
    VOLUNTEER_ID        VARCHAR(36),
    PORTIONS_ALLOCATED  INTEGER         NOT NULL,
    PORTIONS_DELIVERED  INTEGER         DEFAULT 0,
    ROUTE_DISTANCE_KM   DECIMAL(6, 2),
    STATUS              VARCHAR(24)     NOT NULL DEFAULT 'ASSIGNED',
    PICKUP_TIME         TIMESTAMP,
    DELIVERY_TIME       TIMESTAMP,
    DELIVERY_PROOF_NOTE VARCHAR(500),
    CREATED_AT          TIMESTAMP       NOT NULL DEFAULT CURRENT TIMESTAMP,
    CONSTRAINT PK_RESCUES PRIMARY KEY (RESCUE_ID),
    CONSTRAINT FK_RESCUE_DONATION FOREIGN KEY (DONATION_ID) REFERENCES DONATIONS(DONATION_ID),
    CONSTRAINT FK_RESCUE_MATCH FOREIGN KEY (MATCH_ID) REFERENCES MATCHES(MATCH_ID),
    CONSTRAINT FK_RESCUE_DONOR FOREIGN KEY (DONOR_ID) REFERENCES USERS(USER_ID),
    CONSTRAINT FK_RESCUE_NGO FOREIGN KEY (NGO_ID) REFERENCES USERS(USER_ID),
    CONSTRAINT CHK_RESCUE_STATUS CHECK (STATUS IN ('ASSIGNED', 'PICKUP_CONFIRMED', 'PICKED_UP', 'IN_TRANSIT', 'DELIVERED', 'FAILED'))
);

-- ----------------------------------------------------------------------------
-- 7. IMPACT_RECORDS TABLE
-- ----------------------------------------------------------------------------
CREATE TABLE IMPACT_RECORDS (
    IMPACT_ID           VARCHAR(36)     NOT NULL,
    RESCUE_ID           VARCHAR(36)     NOT NULL,
    DONATION_ID         VARCHAR(36)     NOT NULL,
    DONOR_ID            VARCHAR(36)     NOT NULL,
    NGO_ID              VARCHAR(36)     NOT NULL,
    MEALS_DELIVERED     INTEGER         NOT NULL,
    FOOD_WASTE_SAVED_KG DECIMAL(9, 2)   NOT NULL,
    CO2_AVOIDED_KG      DECIMAL(9, 2)   NOT NULL,
    RECORDED_AT         TIMESTAMP       NOT NULL DEFAULT CURRENT TIMESTAMP,
    CONSTRAINT PK_IMPACT PRIMARY KEY (IMPACT_ID),
    CONSTRAINT FK_IMPACT_RESCUE FOREIGN KEY (RESCUE_ID) REFERENCES RESCUES(RESCUE_ID) ON DELETE CASCADE
);

-- ----------------------------------------------------------------------------
-- 8. AUDIT_LOGS TABLE
-- ----------------------------------------------------------------------------
CREATE TABLE AUDIT_LOGS (
    LOG_ID              VARCHAR(36)     NOT NULL,
    ACTOR_ID            VARCHAR(36),
    ACTOR_ROLE          VARCHAR(20),
    ACTION              VARCHAR(64)     NOT NULL,
    ENTITY_TYPE         VARCHAR(32),
    ENTITY_ID           VARCHAR(36),
    REASON              VARCHAR(500),
    TIMESTAMP           TIMESTAMP       NOT NULL DEFAULT CURRENT TIMESTAMP,
    CONSTRAINT PK_AUDIT_LOGS PRIMARY KEY (LOG_ID)
);

-- Indexes for Query Performance in DB2
CREATE INDEX IX_DONATIONS_STATUS ON DONATIONS(STATUS);
CREATE INDEX IX_NGO_VERIF ON NGO_PROFILES(VERIFICATION_STATUS);
CREATE INDEX IX_RESCUES_STATUS ON RESCUES(STATUS);
CREATE INDEX IX_MATCHES_DONATION ON MATCHES(DONATION_ID);
CREATE INDEX IX_AUDIT_TIME ON AUDIT_LOGS(TIMESTAMP);
